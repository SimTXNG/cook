package wails

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"time"

	"gopkg.in/yaml.v3"

	"github.com/simtxng/cook/pkg/config"
)

// WailsProjectConfig represents the Wails v3 build/config.yml structure.
type WailsProjectConfig struct {
	Version          string                  `yaml:"version"`
	Info             WailsInfo               `yaml:"info"`
	DevMode          WailsDevMode            `yaml:"dev_mode"`
	FileAssociations []config.WailsFileAssoc `yaml:"fileAssociations,omitempty"`
	Other            []map[string]any        `yaml:"other,omitempty"`
}

type WailsInfo struct {
	CompanyName       string `yaml:"companyName"`
	ProductName       string `yaml:"productName"`
	ProductIdentifier string `yaml:"productIdentifier"`
	Description       string `yaml:"description"`
	Copyright         string `yaml:"copyright"`
	Comments          string `yaml:"comments"`
	Version           string `yaml:"version"`
}

type WailsDevMode struct {
	RootPath string                   `yaml:"root_path"`
	LogLevel string                   `yaml:"log_level"`
	Debounce int                      `yaml:"debounce"`
	Ignore   WailsDevIgnore           `yaml:"ignore"`
	Executes []config.WailsDevExecute `yaml:"executes"`
}

type WailsDevIgnore struct {
	Dir              []string `yaml:"dir"`
	File             []string `yaml:"file"`
	WatchedExtension []string `yaml:"watched_extension"`
	GitIgnore        bool     `yaml:"git"`
}

func firstNonEmpty(vals ...string) string {
	for _, v := range vals {
		if v != "" {
			return v
		}
	}
	return ""
}

// BuildWailsConfig translates a cook Config into a WailsProjectConfig matching Wails 3 schema.
func BuildWailsConfig(cfg *config.Config) *WailsProjectConfig {
	if cfg == nil {
		cfg = &config.Config{}
	}

	rawVersion := ""
	if cfg.Version != nil {
		rawVersion = cfg.Version.Raw
	}
	ver := firstNonEmpty(cfg.Wails.Version, rawVersion, cfg.Package.Version, "0.0.1")

	company := firstNonEmpty(
		cfg.Wails.CompanyName,
		cfg.Package.Company,
		cfg.Package.Maintainer,
		cfg.Package.Name,
	)

	product := firstNonEmpty(cfg.Wails.ProductName, cfg.Package.ProductName, cfg.Package.Name)

	identifier := firstNonEmpty(
		cfg.Wails.ProductIdentifier,
		cfg.Package.Identifier,
		"com."+firstNonEmpty(cfg.Package.Name, product, "app"),
	)

	description := firstNonEmpty(cfg.Wails.Description, cfg.Package.Description)

	copyright := firstNonEmpty(cfg.Wails.Copyright, cfg.Package.Copyright)
	if copyright == "" {
		copyright = fmt.Sprintf("(c) %d", time.Now().Year())
		if company != "" {
			copyright += ", " + company
		}
	}

	comments := firstNonEmpty(cfg.Wails.Comments, cfg.Package.Description)

	rootPath := firstNonEmpty(cfg.Wails.Dev.RootPath, ".")
	logLevel := firstNonEmpty(cfg.Wails.Dev.LogLevel, "warn")

	debounce := cfg.Wails.Dev.Debounce
	if debounce <= 0 {
		debounce = 1000
	}

	ignoreDirs := cfg.Wails.Dev.IgnoreDirs
	if len(ignoreDirs) == 0 {
		ignoreDirs = []string{
			".git",
			"node_modules",
			firstNonEmpty(cfg.Frontend.Dir, "frontend"),
			firstNonEmpty(cfg.Package.OutputDir, "bin"),
		}
	}

	ignoreFiles := cfg.Wails.Dev.IgnoreFiles
	if len(ignoreFiles) == 0 {
		ignoreFiles = []string{".DS_Store", ".gitignore", ".gitkeep", "*_test.go"}
	}

	watchedExt := cfg.Wails.Dev.WatchedExtension
	if len(watchedExt) == 0 {
		watchedExt = []string{"*.go", "*.js", "*.ts"}
	}

	gitIgnore := true
	if cfg.Wails.Dev.GitIgnore != nil {
		gitIgnore = *cfg.Wails.Dev.GitIgnore
	}

	executes := cfg.Wails.Dev.Executes
	if len(executes) == 0 {
		executes = []config.WailsDevExecute{
			{Cmd: "wails3 build DEV=true", Type: "blocking"},
			{Cmd: "wails3 task common:dev:frontend", Type: "background"},
			{Cmd: "wails3 task run", Type: "primary"},
		}
	}

	return &WailsProjectConfig{
		Version: "3",
		Info: WailsInfo{
			CompanyName:       company,
			ProductName:       product,
			ProductIdentifier: identifier,
			Description:       description,
			Copyright:         copyright,
			Comments:          comments,
			Version:           ver,
		},
		DevMode: WailsDevMode{
			RootPath: rootPath,
			LogLevel: logLevel,
			Debounce: debounce,
			Ignore: WailsDevIgnore{
				Dir:              ignoreDirs,
				File:             ignoreFiles,
				WatchedExtension: watchedExt,
				GitIgnore:        gitIgnore,
			},
			Executes: executes,
		},
		FileAssociations: cfg.Wails.FileAssociations,
	}
}

// GenerateYAML marshals a WailsProjectConfig to YAML with 2-space indentation.
func GenerateYAML(cfg *config.Config) ([]byte, error) {
	wailsCfg := BuildWailsConfig(cfg)
	var buf bytes.Buffer
	buf.WriteString("# Generated by cook for Wails v3. Do not edit manually.\n")
	buf.WriteString("# Source of truth: cook.toml / version file\n\n")

	encoder := yaml.NewEncoder(&buf)
	encoder.SetIndent(2)
	if err := encoder.Encode(wailsCfg); err != nil {
		return nil, fmt.Errorf("failed to encode Wails config to YAML: %w", err)
	}
	if err := encoder.Close(); err != nil {
		return nil, fmt.Errorf("failed to close Wails config YAML encoder: %w", err)
	}
	return buf.Bytes(), nil
}

// resolveConfigPath resolves p against rootDir. Absolute paths are cleaned and
// returned unchanged. Relative paths are resolved against rootDir when it is
// set; otherwise they are resolved against the process working directory, the
// only case where resolution depends on the CWD.
func resolveConfigPath(rootDir, p string) (string, error) {
	if filepath.IsAbs(p) {
		return filepath.Clean(p), nil
	}

	if rootDir != "" {
		root := rootDir
		if !filepath.IsAbs(root) {
			abs, err := filepath.Abs(root)
			if err != nil {
				return "", fmt.Errorf("failed to resolve root directory %q: %w", rootDir, err)
			}
			root = abs
		}
		return filepath.Clean(filepath.Join(root, p)), nil
	}

	abs, err := filepath.Abs(p)
	if err != nil {
		return "", fmt.Errorf("failed to resolve path %q against current working directory: %w", p, err)
	}
	return filepath.Clean(abs), nil
}

// WriteConfigFile generates and writes the Wails config.yml file.
func WriteConfigFile(cfg *config.Config, targetPath string) (string, error) {
	if cfg == nil {
		cfg = &config.Config{}
	}

	if targetPath == "" {
		if cfg.Wails.ConfigFile != "" {
			targetPath = cfg.Wails.ConfigFile
		} else {
			targetPath = "build/config.yml"
		}
	}

	targetPath, err := resolveConfigPath(cfg.RootDir, targetPath)
	if err != nil {
		return "", fmt.Errorf("failed to resolve Wails config path: %w", err)
	}

	if err := os.MkdirAll(filepath.Dir(targetPath), 0755); err != nil {
		return "", fmt.Errorf("failed to create directory for Wails config: %w", err)
	}

	data, err := GenerateYAML(cfg)
	if err != nil {
		return "", err
	}

	if err := os.WriteFile(targetPath, data, 0644); err != nil {
		return "", fmt.Errorf("failed to write Wails config file %s: %w", targetPath, err)
	}

	return targetPath, nil
}
